(async () => {
    const chill = () => new Promise(resolve => setTimeout(resolve, Math.round(Math.random() * 1500))); 
    const icon = {
        'modtype_forum': '💬',
        'modtype_moodleoverflow': '💬',
        'modtype_page': '📄',
        'modtype_feedback': '📣',
        'modtype_assign': '📤',
        'modtype_organizer': '📅',
        'modtype_resource': '📝',
        'modtype_choicegroup': '👥',
        'modtype_ratingallocate': '⚖️',
        'modtype_folder': '📂',
        'modtype_zoom': '☎️',
        'modtype_url': '🌍',
        'modtype_lti': '⛓️',
        'modtype_quiz': '✅'
    };
    // vendored next to this script, see scripts/vendor.mjs
    const externalScripts = [
        'vendor/jszip/jszip.min.js'
    ].map((path) => new URL(path, import.meta.url).href);

    window.define = null;
    window.require = null;
    const scriptsReady = Promise.all(externalScripts.map((script) => new Promise((resolve, reject) => {
        const st = document.createElement('script');
        st.src = script;
        st.addEventListener('load', resolve);
        st.addEventListener('error', () => reject(new Error(`moodleport: failed to load ${script}`)));
        document.body.appendChild(st);
    })));

    let html = '';
    const unsupported = new Map();

    const escapeHtml = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
    // true for markup without any text or media, e.g. Moodle 4.1's empty description elements
    const isEmptyHtml = (fragment) => {
        const tpl = document.createElement('template');
        tpl.innerHTML = fragment;
        return !tpl.content.textContent.trim() && !tpl.content.querySelector('img, video, audio, iframe, object, embed');
    };
    // turns a name taken from Moodle into a single, harmless path segment,
    // so that ZIP entries can't escape the extraction directory (zip slip)
    const safeName = (name) => String(name ?? '')
        .replace(/[\u0000-\u001f\u007f/\\]/g, '_')
        .replace(/^\.+$/, '_') || '_';
    // local copies (in media/) of files embedded in or linked from Moodle's HTML, by URL, so each is downloaded once
    const media = new Map();
    const saveMedia = (url) => {
        if (!media.has(url)) {
            media.set(url, (async () => {
                const name = safeName(decodeURIComponent(new URL(url).pathname.split('/').pop()));
                let path = ['media', name];
                for (let n = 2; zip.file(path.join('/')); n++) {
                    path = ['media', name.replace(/(\.[^.]*)?$/, ` (${n})$1`)];
                }
                await chill();
                const res = await fetch(url);
                if (!res.ok) {
                    return null;
                }
                zip.file(path.join('/'), await res.blob());
                return `./${path.map(encodeURIComponent).join('/')}`;
            })().catch((e) => {
                console.log(e);
                return null;
            }));
        }
        return media.get(url);
    };

    // strips the page's own scripts and styles (any script that slips through, e.g. an inline event handler,
    // is blocked by the CSP in index.html) and replaces images, video, audio and linked files from the
    // Moodle site with local copies; content from other sites stays linked, since CORS usually prevents fetching it
    const cleanHtml = async (fragment) => {
        const tpl = document.createElement('template');
        tpl.innerHTML = fragment;
        tpl.content.querySelectorAll('script, style, noscript, template').forEach((e) => e.remove());
        for (const el of tpl.content.querySelectorAll('img, video, audio, source, track, a[href]')) {
            for (const attr of ['src', 'poster', 'href']) {
                // ./... are files in the backup, linked from markup generated by this script (e.g. Opencast videos)
                if (!el.hasAttribute(attr) || el.getAttribute(attr).startsWith('./')) {
                    continue;
                }
                let url;
                try {
                    url = new URL(el.getAttribute(attr), location.href);
                } catch {
                    continue;
                }
                // links only to files, not to Moodle's pages
                if (!url || url.origin !== location.origin || (attr === 'href' && !url.pathname.includes('/pluginfile.php/'))) {
                    continue;
                }
                const path = await saveMedia(url.href);
                if (path) {
                    el.setAttribute(attr, path);
                    // browsers prefer srcset (still pointing to Moodle) over src
                    el.removeAttribute('srcset');
                }
            }
        }
        return tpl.innerHTML;
    };

    const loader = document.createElement('div');
    loader.style.textAlign = 'center';
    loader.style.position = 'fixed';
    loader.style.bottom = '0px';
    loader.style.right = '0px';
    loader.style.left = '0px';
    loader.style.top = '0px';
    loader.style.display = 'flex';
    loader.style.alignItems = 'center';
    loader.style.justifyContent = 'center';
    loader.style.backgroundColor = 'rgba(0, 0, 0, 0.5)';
    loader.style.zIndex = 99999;

    const content = document.createElement('div');
    content.style.backgroundColor = 'white';
    content.style.borderRadius = '5px';
    content.style.paddingInline = '1em';
    content.style.paddingBlock = '.5em';
    content.style.display = 'block';
    content.style.maxWidth = '300px';
    content.style.maxHeight = '200px';
    content.innerHTML = `<h2>Exporting...</h2>`;

    const progress = document.createElement('progress');
    content.appendChild(progress);
    
    const progressText = document.createElement('div');
    content.appendChild(progressText);
    
    const timeRemaining = document.createElement('small');
    content.appendChild(timeRemaining);

    loader.appendChild(content);

    const updateProgress = (i, t) => {
        progress.max = t;
        progress.value = i;
        progress.innerText = `${i} / ${t}`;
        progressText.innerText = `${i} / ${t}`;
        timeRemaining.innerText = `~${new Date((t - i) * 1000).toISOString().slice(11, 19)} remaining`;
    };

    document.body.appendChild(loader);

    await scriptsReady;

    const zip = new JSZip();
    const parser = new DOMParser();

    // data-activityname holds Moodle's formatted name, i.e. HTML like "A &amp; B"
    const activityName = (activity) => {
        const name = activity.querySelector('[data-activityname]')?.dataset?.activityname;
        return name === undefined ? undefined : parser.parseFromString(name, 'text/html').body.textContent;
    };

    // the course page as sent by the server, before Moodle's JavaScript changed it
    let coursePage = null;
    const getCoursePage = async () => {
        if (!coursePage) {
            await chill();
            coursePage = parser.parseFromString(await (await fetch(location.href)).text(), 'text/html');
        }
        return coursePage;
    };

    // Opencast videos already saved, by URL
    const opencastVideos = new Map();

    // fetches url and parses it as HTML
    const fetchDocument = async (url) => {
        await chill();
        const res = await fetch(url);
        const contentType = res.headers.get('Content-Type')?.replace?.(/;.*$/, '');
        return parser.parseFromString(await res.text(), contentType || 'text/html');
    };

    // URLs of all discussions linked as .../<script>?d=<id> from a forum's (paginated) discussion list;
    // relative links are resolved against the page they're on, not the course page (which link.href would use)
    const discussionUrls = async (viewUrl, script) => {
        const urls = new Set();
        const pages = [viewUrl];
        for (let i = 0; i < pages.length; i++) {
            const doc = await fetchDocument(pages[i]);
            for (const link of doc.querySelectorAll(`a[href*="${script.split('/').pop()}?d="]`)) {
                const url = new URL(link.getAttribute('href'), pages[i]);
                if (!url.pathname.endsWith(`/${script}`)) {
                    continue;
                }
                if (!url.searchParams.has('parent')) {
                    url.hash = '';
                    urls.add(url.href);
                }
            }
            for (const link of doc.querySelectorAll('.pagination a[href]')) {
                const page = new URL(link.getAttribute('href'), pages[i]);
                page.hash = '';
                if (page.pathname === new URL(viewUrl).pathname && !pages.includes(page.href)) {
                    pages.push(page.href);
                }
            }
        }
        return [...urls];
    };

    // downloads the linked files into dir (numbering duplicate names), returns a list of them
    const saveAttachments = async (links, dir) => {
        const items = [];
        for (const url of new Set(links.map((a) => a.href))) {
            const name = safeName(decodeURIComponent(new URL(url).pathname.split('/').pop()));
            let path = [...dir, name];
            for (let n = 2; zip.file(path.join('/')); n++) {
                path = [...dir, name.replace(/(\.[^.]*)?$/, ` (${n})$1`)];
            }
            await chill();
            zip.file(path.join('/'), await (await fetch(url)).blob());
            items.push(`<li><a href="./${path.map(encodeURIComponent).join('/')}">📎 ${escapeHtml(path.at(-1))}</a></li>`);
        }
        return items.length ? `<ul class="attachments">${items.join('')}</ul>` : '';
    };

    const postHtml = (classes, meta, content, attachments, replies = '') =>
        `<div class="${['post', classes].filter(Boolean).join(' ')}"><p class="meta">${meta.filter(Boolean).map(escapeHtml).join(' · ')}</p>`
        + `${content}${attachments}${replies}</div>`;

    // a forum post (article[data-region="post"]) with its nested replies
    const forumPost = async (article, dir) => {
        const own = (selector) => [...article.querySelectorAll(selector)].filter((e) => e.closest('[data-region="post"]') === article);
        const subject = own('[data-region-content="forum-post-core-subject"]')[0]?.textContent?.trim();
        const author = own('header a[href*="/user/view.php"]')[0]?.textContent?.trim();
        const time = own('header time')[0]?.textContent?.trim();
        const attachments = await saveAttachments(own('a[href*="/mod_forum/attachment/"]'), dir);
        let replies = '';
        for (const reply of article.querySelectorAll('[data-region="post"]')) {
            if (reply.parentElement.closest('[data-region="post"]') === article) {
                replies += await forumPost(reply, dir);
            }
        }
        return postHtml('', [subject, author, time], own('.post-content-container')[0]?.innerHTML || '', attachments, replies);
    };

    // a discussion page's top-level forum posts, which contain their replies (or all posts, in flat display mode)
    const forumPosts = (doc) => [...doc.querySelectorAll('[data-region="post"]')]
        .filter((post) => !post.parentElement.closest('[data-region="post"]'));

    const course = document.querySelector('.page-header-headings h1')?.innerText || '';
    if (course) {
        html += `<h1>${escapeHtml(course)}</h1>\n`;
    }

    // a section's own activities, without those of a subsection (Moodle 4.5+), which is
    // an activity containing its own .course-section
    const activitiesOf = (section) => [...section.querySelectorAll('.activity')]
        .filter((a) => a.parentElement.closest('.course-section') === section);

    // sections and activities in order, with their heading level
    const entries = [];
    for (const section of document.querySelectorAll('.course-section')) {
        if (section.parentElement.closest('.activity')) {
            continue; // subsection, added below
        }
        entries.push({ section, level: 2 });
        for (const activity of activitiesOf(section)) {
            const subsection = activity.querySelector('.course-section');
            if (subsection) {
                entries.push({ section: subsection, level: 3 });
                entries.push(...activitiesOf(subsection).map((a) => ({ activity: a, level: 4 })));
            } else {
                entries.push({ activity, level: 3 });
            }
        }
    }

    let current = 0;
    updateProgress(current, entries.length);

    for (const { section, activity, level } of entries) {
        if (section) {
            const title = section.querySelector('.sectionname')?.innerText || '';
            if (title) {
                html += `<h${level}>${escapeHtml(title)}</h${level}>\n`;
            }
        } else {
            try {
                const type = [...activity.classList].find(e => String(e).startsWith('modtype_'));
                let contentHtml = null;
                let href = null;

                switch (type) {
                    case 'modtype_label': {
                        // just the label's text, without Moodle's activity markup (e.g. the bulk edit checkbox)
                        const text = activity.querySelector('.description-inner') || activity.querySelector('.activity-altcontent');
                        contentHtml = (text || activity).innerHTML;
                        break;
                    }

                    case 'modtype_url':
                    case 'modtype_zoom':
                    case 'modtype_quiz':
                    case 'modtype_feedback':
                    case 'modtype_organizer':
                    case 'modtype_choicegroup':
                    case 'modtype_ratingallocate':
                        href = activity.querySelector('.aalink')?.href;
                        break;

                    case 'modtype_forum': {
                        href = activity.querySelector('.aalink')?.href;
                        if (!href) {
                            break;
                        }
                        const dir = safeName(activityName(activity));
                        const urls = await discussionUrls(href, 'mod/forum/discuss.php');
                        // a "single simple discussion" forum shows its posts on the forum's own page
                        for (const url of urls.length ? urls : [href]) {
                            const posts = forumPosts(await fetchDocument(url));
                            if (!posts.length) {
                                continue;
                            }
                            const title = posts[0].querySelector('[data-region-content="forum-post-core-subject"]')?.textContent?.trim() || '';
                            let discussion = '';
                            for (const post of posts) {
                                discussion += await forumPost(post, [dir, safeName(title)]);
                            }
                            contentHtml = (contentHtml || '')
                                + `<div class="discussion"><h${level + 1}>${escapeHtml(title)}</h${level + 1}>${discussion}</div>`;
                        }
                        break;
                    }

                    case 'modtype_moodleoverflow': {
                        href = activity.querySelector('.aalink')?.href;
                        if (!href) {
                            break;
                        }
                        const dir = safeName(activityName(activity));
                        for (const url of await discussionUrls(href, 'mod/moodleoverflow/discussion.php')) {
                            const doc = await fetchDocument(url);
                            const title = doc.querySelector('.discussionname')?.textContent?.trim() || '';
                            let discussion = '';
                            // the question, then the answers (accepted ones first), each followed by its comments
                            for (const post of doc.querySelectorAll('.moodleoverflowpost')) {
                                const kind = post.matches('.starter') ? 'question' : post.matches('.moodleoverflowcomment') ? 'comment' : 'answer';
                                const text = post.querySelector('.post-text')?.cloneNode(true);
                                text?.querySelector('a.anchor')?.remove();
                                const info = post.querySelector('.post-info .leftbox');
                                // .user-details, since the avatar is a profile link too (in older versions)
                                const author = (info?.querySelector('.user-details a[href*="/user/view.php"]')
                                    || info?.querySelector('a[href*="/user/view.php"]'))?.textContent?.trim();
                                // comments only show a short "author - time"
                                const time = post.querySelector('.user-action-time')?.textContent?.trim()
                                    || info?.querySelector('.text-muted')?.textContent?.split(' - ')?.pop()?.trim();
                                const votes = kind === 'answer' ? post.querySelector('.votecount')?.textContent?.trim() : null;
                                const attachments = await saveAttachments(
                                    [...post.querySelectorAll('.attachments a[href*="/mod_moodleoverflow/attachment/"]')], [dir, safeName(title)]);
                                discussion += postHtml(`${kind}${post.matches('.markedsolution') ? ' solution' : ''}`, [
                                    { question: '❓ Question', answer: '💡 Answer', comment: '💬 Comment' }[kind],
                                    author, time,
                                    votes && `${votes} votes`,
                                    post.matches('.markedsolution') && '✅ marked as solution',
                                    post.matches('.markedhelpful') && '👍 marked as helpful',
                                ], text?.innerHTML || '', attachments);
                            }
                            contentHtml = (contentHtml || '')
                                + `<div class="discussion"><h${level + 1}>${escapeHtml(title)}</h${level + 1}>${discussion}</div>`;
                        }
                        break;
                    }

                    case 'modtype_page': {
                        await chill();
                        const res = await fetch(activity.querySelector('.aalink')?.href);
                        const contentType = res.headers.get('Content-Type')?.replace?.(/;.*$/, '');
                        const body = await res.text();
                        const dom = parser.parseFromString(body, contentType || 'text/html');
                        // just the page's text, without the surrounding layout (header, "Last modified", ...)
                        contentHtml = (dom.querySelector('#page-content [role=main] > .generalbox') || dom.querySelector('#page-content')).innerHTML;
                        break;
                    }

                    case 'modtype_resource': {
                        const resource = activity.querySelector('.aalink')?.href;
                        await chill();
                        const res = await fetch(resource);
                        const contentType = res.headers.get('Content-Type')?.replace?.(/;.*$/, '');
                        const body = await res.blob();
                        const filename = safeName(decodeURIComponent(new URL(res.url || resource)?.pathname?.split?.('/')?.pop?.()));
                        zip.file(filename, body);
                        href = `./${encodeURIComponent(filename)}`;
                        break;
                    }

                    case 'modtype_folder': {
                        // parse the server's HTML, not the live DOM (Moodle <= 4.2 turns it into a YUI tree):
                        // nested <ul><li>, labelled by .fp-filename-icon (<= 4.2) or <p> (4.3+)
                        const resource = activity.querySelector('.aalink')?.href;
                        let root = null;
                        if (resource) {
                            await chill();
                            const res = await fetch(resource);
                            const contentType = res.headers.get('Content-Type')?.replace?.(/;.*$/, '');
                            const dom = parser.parseFromString(await res.text(), contentType || 'text/html');
                            root = dom.querySelector('#page-content .filemanager');
                        } else {
                            root = (await getCoursePage()).getElementById(activity.id)?.querySelector('.filemanager');
                        }

                        // downloads all files below li and returns its tree as { filename, isFolder, link, children }
                        const walk = async (li, path) => {
                            const label = li.querySelector(':scope > .fp-filename-icon, :scope > p')?.cloneNode(true);
                            label?.querySelectorAll('.visually-hidden').forEach((e) => e.remove());
                            const filename = label?.textContent?.replace(/\s+/g, ' ')?.trim() || '';
                            const isFolder = /\/f\/folder/.test(label?.querySelector('img.icon')?.src || '');
                            const fileHref = label?.querySelector('a[href]')?.href;
                            path = [...path, safeName(filename)];
                            const node = { filename, isFolder, link: null, children: [] };

                            if (fileHref) {
                                await chill();
                                const res = await fetch(fileHref);
                                const body = await res.blob();
                                zip.file(path.join('/'), body);
                                node.link = `./${path.map(encodeURIComponent).join('/')}`;
                            }

                            node.children = await Promise.all([...li.querySelectorAll(':scope > ul > li')].map((c) => walk(c, path)));
                            return node;
                        };

                        if (root) {
                            // the top-level entry is the folder itself (unnamed on the folder's own page),
                            // so its contents are stored in a directory named after the activity
                            const name = activityName(activity);
                            const top = [...root.querySelectorAll(':scope > ul > li > ul > li')];
                            const tree = await Promise.all(top.map((li) => walk(li, [safeName(name)])));
                            const label = (n) => `${n.isFolder ? '📂' : '📝'} ${n.filename}`;
                            const renderHtml = (nodes) => nodes.length ? `<ul>${nodes.map((n) =>
                                `<li>${n.link ? `<a href="${escapeHtml(n.link)}">${escapeHtml(label(n))}</a>` : escapeHtml(label(n))}${renderHtml(n.children)}</li>`
                            ).join('')}</ul>` : '';
                            contentHtml = renderHtml(tree);
                        }

                        break;
                    }

                    case 'modtype_lti': {
                        href = activity.querySelector('.aalink')?.href;
                        if (!href) {
                            break;
                        }
                        // the launch page has a form that logs the user in to the tool and opens it
                        const form = (await fetchDocument(href.replace('lti/view', 'lti/launch'))).querySelector('#ltiLaunchForm');
                        const fd = form && new FormData(form);
                        // Opencast: a single video (custom_id) or a whole series (custom_series)
                        const episode = fd?.get('custom_id');
                        const series = fd?.get('custom_series');
                        if (!episode && !series) {
                            break;
                        }
                        const opencast = new URL(form.getAttribute('action'), href).origin;

                        // log in to Opencast; it redirects to its player, which has no CORS headers, so the
                        // response can't be read (no-cors), but the request and its session cookie still count
                        await chill();
                        await fetch(form.getAttribute('action'), { method: 'POST', mode: 'no-cors', credentials: 'include', body: new URLSearchParams(fd) })
                            .catch((e) => console.log(e));

                        // the episodes' metadata, page by page; Opencast 14+ returns { total, result: [...] },
                        // older versions { 'search-results': { total, result } }, with single results not wrapped in an array
                        const list = (v) => (Array.isArray(v) ? v : v ? [v] : []);
                        const episodes = [];
                        for (let offset = 0; ; ) {
                            const query = episode ? `id=${encodeURIComponent(episode)}` : `sid=${encodeURIComponent(series)}`;
                            await chill();
                            const res = await fetch(`${opencast}/search/episode.json?${query}&limit=20&offset=${offset}`, { credentials: 'include' });
                            const json = await res.json();
                            const page = json['search-results'] || json;
                            const results = list(page.result);
                            episodes.push(...results);
                            offset += results.length;
                            if (!results.length || offset >= Number(page.total)) {
                                break;
                            }
                        }

                        const dir = safeName(activityName(activity));
                        const videos = [];
                        for (const result of episodes) {
                            const mediapackage = result.mediapackage || result;
                            const title = result.dc?.title?.[0] || mediapackage.title || result.id || mediapackage.id;
                            // the best MP4 per flavor (e.g. presentation/delivery for the slides, presenter/delivery for the camera)
                            const best = new Map();
                            for (const track of list(mediapackage.media?.track).filter((t) => t.mimetype === 'video/mp4' && t.url)) {
                                const flavor = track.type || track.flavor || '';
                                const pixels = (t) => (t?.video?.resolution || '0x0').split('x').reduce((a, b) => a * b, 1);
                                if (pixels(track) >= pixels(best.get(flavor))) {
                                    best.set(flavor, track);
                                }
                            }
                            for (const [flavor, track] of best) {
                                const name = safeName(`${title}${best.size > 1 ? ` (${flavor.split('/')[0]})` : ''}.mp4`);
                                // a video that's also in another activity (e.g. a series and a single episode of it) is saved once
                                if (!opencastVideos.has(track.url)) {
                                    const path = [dir, name];
                                    await chill();
                                    const video = await fetch(track.url, { credentials: 'include' });
                                    zip.file(path.join('/'), await video.blob());
                                    opencastVideos.set(track.url, `./${path.map(encodeURIComponent).join('/')}`);
                                }
                                const src = opencastVideos.get(track.url);
                                videos.push(`<figure><video controls preload="metadata" src="${escapeHtml(src)}"></video>`
                                    + `<figcaption><a href="${escapeHtml(src)}">🎬 ${escapeHtml(name)}</a></figcaption></figure>`);
                            }
                        }
                        if (videos.length) {
                            contentHtml = videos.join('');
                        }
                        break;
                    }

                    case 'modtype_assign': {
                        href = activity.querySelector('.aalink')?.href;
                        if (!href) {
                            break;
                        }

                        await chill();
                        const res = await fetch(href);
                        const contentType = res.headers.get('Content-Type')?.replace?.(/;.*$/, '');
                        const dom = parser.parseFromString(await res.text(), contentType || 'text/html');

                        // downloads the files linked as .../<area>/<itemid>/<path> into dir, returns a list of them
                        const download = async (selector, area, dir) => {
                            const items = [];
                            for (const url of new Set([...dom.querySelectorAll(selector)].map((a) => a.href))) {
                                const path = new URL(url).pathname.split(`/${area}/`)[1]
                                    .split('/').slice(1).map((p) => safeName(decodeURIComponent(p)));
                                const zipPath = [...dir, ...path];
                                await chill();
                                zip.file(zipPath.join('/'), await (await fetch(url)).blob());
                                items.push(`<li><a href="./${zipPath.map(encodeURIComponent).join('/')}">📝 ${escapeHtml(path.join('/'))}</a></li>`);
                            }
                            return items.length ? `<ul>${items.join('')}</ul>` : '';
                        };

                        // files attached to the description (e.g. the task sheet), only shown on the assignment's page
                        const dir = safeName(activityName(activity));
                        contentHtml = await download('#intro a[href*="/mod_assign/introattachment/"]', 'mod_assign/introattachment', [dir]);

                        // the user's own submission
                        const submission = await download('.submissionstatustable a[href*="/assignsubmission_file/submission_files/"]',
                            'assignsubmission_file/submission_files', [dir, 'My submission']);
                        if (submission) {
                            const status = dom.querySelector('.submissionstatustable td[class*="submissionstatus"]')?.textContent?.trim();
                            contentHtml += `<div class="submission"><p>📤 <strong>My submission</strong>${status ? ` (${escapeHtml(status)})` : ''}</p>${submission}</div>`;
                        }
                        break;
                    }

                    default:
                        console.warn(`moodleport: unsupported activity type '${type}', saving link only`);
                        unsupported.set(type, (unsupported.get(type) || 0) + 1);
                        href = activity.querySelector('.aalink')?.href;
                        break;
                }

                if (type !== 'modtype_label') {
                    const name = activityName(activity);
                    const label = `${icon[type] ?? '🔗'} ${name}`;
                    if (name && href) {
                        html += `<h${level}><a href="${escapeHtml(href)}">${escapeHtml(label)}</a></h${level}>\n`;
                    } else if (name) {
                        html += `<h${level}>${escapeHtml(label)}</h${level}>\n`;
                    }
                }

                // a label's text is its description, so it's already in contentHtml
                if (type !== 'modtype_folder' && type !== 'modtype_label') {
                    // .activity-description since Moodle 4.3, .description before
                    const description = (activity.querySelector('.activity-description') || activity.querySelector('.description .description-inner') || activity.querySelector('.description'))?.innerHTML;
                    if (description && !isEmptyHtml(description)) {
                        html += `<blockquote>${await cleanHtml(description)}</blockquote>\n`;
                    }
                }

                if (contentHtml) {
                    html += await cleanHtml(contentHtml) + '\n';
                }
            } catch (e) {
                console.log(e);
            }
        }

        current += 1;
        updateProgress(current, entries.length);
    }

    // dedent the template before inserting the content, so that indentation
    // inside the course's own markup (e.g. in <pre> blocks) is preserved
    zip.file('index.html', `
      <!DOCTYPE html>
      <html>
        <head>
          <meta charset="UTF-8">
          <meta http-equiv="Content-Security-Policy" content="script-src 'none'; object-src 'none'">
          <meta name="viewport" content="width=device-width, initial-scale=1.0">
          <title>${escapeHtml(course || 'Moodle course backup')}</title>
          <style>
            body { font-family: system-ui, sans-serif; line-height: 1.5; max-width: 50em; margin: 0 auto; padding: 1em; color: #222; }
            h2 { border-bottom: 1px solid #ccc; margin-top: 2em; }
            blockquote { margin-inline: 0; padding-left: 1em; border-left: 3px solid #ccc; color: #555; }
            img, video, iframe { max-width: 100%; height: auto; }
            table { border-collapse: collapse; }
            td, th { border: 1px solid #ccc; padding: .25em .5em; }
            .post { border-left: 3px solid #ccc; padding-left: 1em; margin: .75em 0; }
            .post .meta { color: #555; font-size: .9em; margin: 0; }
            .post.comment { margin-left: 2em; }
            .post.solution { border-left-color: #2a7; }
            .attachments { list-style: none; padding: 0; }
            figure { margin: 1em 0; }
            video { max-width: 100%; }
            .submission { border: 2px solid #2a7; border-radius: 4px; padding: 0 1em; margin: 1em 0; }
          </style>
        </head>
        <body>
          <!-- content -->
        </body>
      </html>
    `.replace(/^ {6}/gm, '').trim().replace('<!-- content -->', () => html));

    const blob = await zip.generateAsync({ type: 'blob' });
    const downloadUrl = URL.createObjectURL(blob);
    const download = document.createElement('a');
    download.href = downloadUrl;
    download.download = `${course.replace(/[^A-Za-z0-9]/gi, '_')}.zip`;
    document.body.appendChild(download);
    download.click();
    download.remove();
    // revoking right away can abort the download in some browsers
    setTimeout(() => URL.revokeObjectURL(downloadUrl), 60 * 1000);

    if (unsupported.size === 0) {
        loader.remove();
        return;
    }

    content.style.maxHeight = '80vh';
    content.style.maxWidth = '400px';
    content.style.overflowY = 'auto';
    content.style.textAlign = 'left';
    content.replaceChildren();

    const heading = document.createElement('h2');
    heading.innerText = '⚠️ Export finished with warnings';
    content.appendChild(heading);

    const explanation = document.createElement('p');
    explanation.innerText = 'The following activity types are not supported yet. Only a link to them was saved in the backup:';
    content.appendChild(explanation);

    const list = document.createElement('ul');
    for (const [type, count] of unsupported) {
        const item = document.createElement('li');
        item.innerText = `${type.replace(/^modtype_/, '')} (${count}×)`;
        list.appendChild(item);
    }
    content.appendChild(list);

    const issue = document.createElement('p');
    issue.innerHTML = 'Feel free to report them on <a href="https://github.com/ech0-de/moodleport/issues" target="_blank" rel="noreferrer noopener">GitHub</a>.';
    content.appendChild(issue);

    const close = document.createElement('button');
    close.innerText = 'Close';
    close.addEventListener('click', () => loader.remove());
    content.appendChild(close);
})().then(console.log).catch(console.log);
